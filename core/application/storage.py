"""storage.py — порт (интерфейс) объектного хранилища файлов.

За что отвечает модуль:
    Объявляет абстракцию FileStorage — «куда и как класть файлы» (фото, договоры)
    и «как отдать клиенту рабочую ссылку», не привязываясь к конкретному хранилищу.
    Прикладной/презентационный слой зависит от этого интерфейса, а конкретная
    реализация (S3/MinIO) внедряется снаружи. Это принцип инверсии зависимостей
    (DIP): хранилище можно заменить, не меняя остальной код.

Модель доступа к файлам:
    • внутрь бакета кладём объект по КЛЮЧУ (object_key) — он не отдаётся наружу;
    • клиенту выдаём короткоживущую presigned-ссылку (generate_presigned_get_url),
      по которой файл можно скачать напрямую из хранилища БЕЗ JWT приложения.
    Так медиа-трафик не идёт через backend, а ссылки протухают по таймауту.
"""

from __future__ import annotations

from abc import ABC, abstractmethod


class FileStorage(ABC):
    """Абстрактное объектное хранилище: кладёт байты по ключу и выдаёт ссылки."""

    @abstractmethod
    def put(self, object_key: str, data: bytes, content_type: str) -> None:
        """Сохраняет объект в хранилище под заданным ключом.

        object_key   — внутренний ключ объекта в бакете (наружу не отдаётся);
        data         — содержимое файла в байтах;
        content_type — MIME-тип (влияет на Content-Type при отдаче объекта).
        """
        raise NotImplementedError

    @abstractmethod
    def generate_presigned_get_url(self, object_key: str, expires_in: int) -> str:
        """Возвращает короткоживущую presigned-ссылку на скачивание объекта.

        Ссылка действует expires_in секунд и не требует авторизации приложения:
        её можно подставить напрямую в <img>/вьювер. Подпись включает host, поэтому
        реализация обязана генерировать URL под ПУБЛИЧНЫМ адресом хранилища.
        """
        raise NotImplementedError

    @abstractmethod
    def delete(self, object_key: str) -> None:
        """Удаляет объект из хранилища по ключу (идемпотентно)."""
        raise NotImplementedError
