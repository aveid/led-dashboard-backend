"""pagination.py — простая пагинация списков (limit/offset) для FastAPI.

За что отвечает: даёт единый способ ограничивать размер выборки в списочных
эндпоинтах, когда вызывающий явно этого просит. Используется как зависимость:
params: PaginationParams = Depends().

Для MVP этого достаточно; при необходимости позже добавим общий конверт ответа
с total/страницами.
"""

from __future__ import annotations

from dataclasses import dataclass

from fastapi import Query


@dataclass
class PaginationParams:
    """Параметры постраничной выдачи, приходящие из query-строки запроса.

    limit  — сколько записей вернуть (1..200); по умолчанию не задан — значит
             «без ограничения» (весь список, как и обещает контракт «bare array»
             для этого эндпоинта). Без явного дефолта в 50 список экранов молча
             обрезался бы до первых 50 записей на каждый GET /api/screens —
             это и обрезало карту/дашборд при количестве экранов больше 50.
    offset — сколько записей пропустить от начала (для «следующей страницы»).
    """

    limit: int | None = Query(None, ge=1, le=200, description="Сколько записей вернуть")
    offset: int = Query(0, ge=0, description="Сколько записей пропустить")
