"""exceptions.py — иерархия доменных исключений.

За что отвечает модуль:
    Определяет ошибки уровня бизнес-логики, независимые от Django и HTTP.
    Домен и use cases выбрасывают именно эти исключения, а слой представления
    (DRF) переводит их в корректные HTTP-ответы (см. core/api/exception_handler.py).

Почему исключения, а не коды возврата:
    В Python исключения — идиоматичный способ прервать выполнение при нарушении
    правила. Мы разделяем их по смыслу (валидация / бизнес-правило / не найдено),
    чтобы представление могло отдать правильный статус (400 / 409 / 404) без
    знания деталей домена. Это соблюдает принцип разделения ответственности (SRP).
"""

from __future__ import annotations


class DomainError(Exception):
    """Базовая доменная ошибка. От неё наследуются все остальные.

    Ловля этого типа в обработчике представления гарантирует, что ни одна
    доменная ошибка не «утечёт» наружу необработанной.
    """


class ValidationError(DomainError):
    """Некорректные входные данные (нарушение инвариантов при создании объекта).

    Пример: отрицательная сумма аренды, широта вне диапазона [-90; 90].
    Слой представления переводит в HTTP 400 Bad Request.
    """


class BusinessRuleViolation(DomainError):
    """Нарушение бизнес-правила при валидном по форме запросе.

    Пример: попытка активировать экран без прикреплённого договора и фото.
    Слой представления переводит в HTTP 409 Conflict.
    """


class UnprocessableEntityError(DomainError):
    """Данные синтаксически верны, но семантически недопустимы (422 Unprocessable Entity).

    В отличие от ValidationError (→ 400 «битый запрос»), это про валидацию по
    смыслу: значение прошло проверку формы, но нарушает прикладное правило —
    например, дубликат уникального имени типа экрана или ссылка на несуществующий
    тип экрана (`screen_type_id`). Слой представления переводит в HTTP 422 — как
    того требует контракт с фронтендом (см. backend-instruction §5, §7).
    """


class NotFoundError(DomainError):
    """Запрошенная сущность не найдена (например, экран по несуществующему id).

    Слой представления переводит в HTTP 404 Not Found.
    """


class UnsupportedMediaTypeError(DomainError):
    """Тип загружаемого файла вне списка разрешённых (MIME не в allowlist).

    Пример: попытка загрузить .exe как фото экрана.
    Слой представления переводит в HTTP 415 Unsupported Media Type.
    """


class PayloadTooLargeError(DomainError):
    """Загружаемый файл превышает допустимый размер для своего типа.

    Слой представления переводит в HTTP 413 Payload Too Large.
    """
