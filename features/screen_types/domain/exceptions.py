"""exceptions.py — доменные исключения справочника типов экрана.

Здесь живёт ошибка, специфичная для типов экрана и не сводимая к общим доменным
исключениям из core: попытка удалить тип, на который ссылаются экраны. Она несёт
число ссылающихся экранов (used_by_count), чтобы слой представления собрал
машиночитаемое тело ответа 409 (см. backend-instruction §6).
"""

from __future__ import annotations


class ScreenTypeInUseError(Exception):
    """Тип экрана нельзя удалить: на него ссылается хотя бы один экран (→ 409).

    Несёт used_by_count — сколько экранов используют тип. Слой представления
    (router) ловит это исключение и отдаёт 409 с телом
    {"code": "screen_type_in_use", "message": ..., "used_by_count": N}.
    Не регистрируется в глобальном обработчике ошибок намеренно: тело ответа
    специфично и собирается в роутере (как ATTACHMENT_LIMIT_EXCEEDED у вложений).
    """

    def __init__(self, used_by_count: int) -> None:
        self.used_by_count = used_by_count
        super().__init__(
            f"Нельзя удалить тип: он используется экранами ({used_by_count})"
        )
